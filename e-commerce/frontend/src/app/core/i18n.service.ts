@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<Language>(this.read());
  readonly isBangla = computed(() => this.lang() === 'bn');

  t(key: string): string {
    const entry = DICTIONARY[key];
    if (!entry) return key;
    return entry[this.lang()];
  }

  toggle(): void {
    this.set(this.lang() === 'en' ? 'bn' : 'en');
  }

  set(lang: Language): void {
    this.lang.set(lang);
    if (typeof localStorage !== 'undefined') localStorage.setItem('stitchstyle.lang', lang);
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
  }

  private read(): Language {
    if (typeof localStorage === 'undefined') return 'en';
    return localStorage.getItem('stitchstyle.lang') === 'bn' ? 'bn' : 'en';
  }
}
