-- Stitch & Style — Phase 0/1/2 baseline schema.
-- PostgreSQL 18; all timestamps are UTC timestamptz.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    google_sub VARCHAR(255),
    picture_url VARCHAR(1024),
    phone VARCHAR(32),
    role VARCHAR(32) NOT NULL DEFAULT 'CUSTOMER',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_role_check CHECK (role IN ('ADMIN', 'MANAGER', 'CUSTOMER'))
);
CREATE UNIQUE INDEX users_email_lower_uk ON users (lower(email));
CREATE UNIQUE INDEX users_google_sub_uk ON users (google_sub) WHERE google_sub IS NOT NULL;

CREATE TABLE media_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    storage_key VARCHAR(512) NOT NULL,
    original_filename VARCHAR(512) NOT NULL,
    mime_type VARCHAR(128) NOT NULL,
    byte_size BIGINT NOT NULL,
    width INTEGER,
    height INTEGER,
    checksum_sha256 VARCHAR(128) NOT NULL,
    created_by BIGINT REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT media_assets_storage_key_uk UNIQUE (storage_key)
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES categories (id),
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    description TEXT,
    image_media_id BIGINT REFERENCES media_assets (id),
    size_type VARCHAR(32) NOT NULL DEFAULT 'LETTER',
    display_order INTEGER NOT NULL DEFAULT 0,
    depth INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    show_on_home BOOLEAN NOT NULL DEFAULT FALSE,
    show_in_navbar BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT categories_slug_uk UNIQUE (slug),
    CONSTRAINT categories_size_type_check CHECK (size_type IN ('LETTER', 'WAIST', 'SHOE', 'FREE', 'CUSTOM'))
);
CREATE INDEX categories_parent_order_idx ON categories (parent_id, display_order);
CREATE INDEX categories_home_idx ON categories (is_active, show_on_home, display_order);
CREATE INDEX categories_navbar_idx ON categories (is_active, show_in_navbar, display_order);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories (id),
    name_i18n JSONB NOT NULL DEFAULT '{}'::jsonb,
    slug VARCHAR(255) NOT NULL,
    description_i18n JSONB NOT NULL DEFAULT '{}'::jsonb,
    base_price NUMERIC(12,2) NOT NULL,
    discount_price NUMERIC(12,2),
    size_type VARCHAR(32) NOT NULL DEFAULT 'LETTER',
    origin_country VARCHAR(128),
    brand VARCHAR(128),
    model VARCHAR(128),
    delivery_estimate VARCHAR(128),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT products_slug_uk UNIQUE (slug),
    CONSTRAINT products_price_check CHECK (base_price >= 0 AND (discount_price IS NULL OR discount_price >= 0)),
    CONSTRAINT products_size_type_check CHECK (size_type IN ('LETTER', 'WAIST', 'SHOE', 'FREE', 'CUSTOM'))
);
CREATE INDEX products_category_active_idx ON products (category_id, is_active, created_at DESC);
CREATE INDEX products_featured_idx ON products (is_active, is_featured, created_at DESC);

CREATE TABLE product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    media_asset_id BIGINT NOT NULL REFERENCES media_assets (id),
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX product_images_product_idx ON product_images (product_id, sort_order);

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    size_label VARCHAR(64) NOT NULL,
    sku VARCHAR(128) NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    price_override NUMERIC(12,2),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT product_variants_sku_uk UNIQUE (sku),
    CONSTRAINT product_variants_stock_check CHECK (stock_quantity >= 0 AND reserved_quantity >= 0 AND reserved_quantity <= stock_quantity)
);
CREATE INDEX product_variants_product_idx ON product_variants (product_id, size_label);

CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT carts_user_uk UNIQUE (user_id)
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    variant_id BIGINT NOT NULL REFERENCES product_variants (id),
    quantity INTEGER NOT NULL,
    selected BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT cart_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT cart_items_cart_variant_uk UNIQUE (cart_id, variant_id)
);

CREATE TABLE delivery_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    district VARCHAR(255),
    delivery_charge NUMERIC(12,2) NOT NULL DEFAULT 0,
    free_shipping_threshold NUMERIC(12,2),
    sla_days INTEGER,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT delivery_areas_charge_check CHECK (delivery_charge >= 0)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL,
    public_token VARCHAR(64) NOT NULL,
    user_id BIGINT REFERENCES users (id),
    guest_id VARCHAR(128),
    customer_name VARCHAR(255) NOT NULL,
    customer_phone VARCHAR(32) NOT NULL,
    shipping_address TEXT NOT NULL,
    delivery_area_id BIGINT NOT NULL REFERENCES delivery_areas (id),
    subtotal NUMERIC(12,2) NOT NULL,
    delivery_charge NUMERIC(12,2) NOT NULL,
    discount_total NUMERIC(12,2) NOT NULL DEFAULT 0,
    grand_total NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(32) NOT NULL,
    payment_status VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    cancel_reason VARCHAR(255),
    note TEXT,
    courier_name VARCHAR(255),
    tracking_number VARCHAR(255),
    placed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT orders_order_number_uk UNIQUE (order_number),
    CONSTRAINT orders_public_token_uk UNIQUE (public_token),
    CONSTRAINT orders_payment_method_check CHECK (payment_method IN ('COD', 'BKASH', 'SSLCOMMERZ')),
    CONSTRAINT orders_payment_status_check CHECK (payment_status IN ('UNPAID', 'INITIATED', 'PAID', 'FAILED', 'EXPIRED', 'REFUNDED')),
    CONSTRAINT orders_status_check CHECK (status IN ('PENDING', 'SHIPPED', 'DELIVERED', 'CANCELLED'))
);
CREATE INDEX orders_user_idx ON orders (user_id, placed_at DESC);
CREATE INDEX orders_status_idx ON orders (status, placed_at DESC);
CREATE INDEX orders_phone_idx ON orders (customer_phone);
CREATE INDEX orders_placed_idx ON orders (placed_at DESC);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id),
    variant_id BIGINT NOT NULL REFERENCES product_variants (id),
    product_name_snapshot VARCHAR(255) NOT NULL,
    size_label_snapshot VARCHAR(64) NOT NULL,
    sku_snapshot VARCHAR(128) NOT NULL,
    unit_price_snapshot NUMERIC(12,2) NOT NULL,
    quantity INTEGER NOT NULL,
    line_total NUMERIC(12,2) NOT NULL,
    CONSTRAINT order_items_quantity_check CHECK (quantity > 0)
);
CREATE INDEX order_items_order_idx ON order_items (order_id);

CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    provider VARCHAR(32) NOT NULL,
    provider_txn_id VARCHAR(255) NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'BDT',
    status VARCHAR(32) NOT NULL,
    raw_response JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT payments_provider_txn_uk UNIQUE (provider, provider_txn_id)
);
CREATE INDEX payments_order_idx ON payments (order_id);

CREATE TABLE stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    variant_id BIGINT NOT NULL REFERENCES product_variants (id),
    quantity INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT stock_reservations_quantity_check CHECK (quantity > 0),
    CONSTRAINT stock_reservations_status_check CHECK (status IN ('ACTIVE', 'COMMITTED', 'RELEASED', 'EXPIRED'))
);
CREATE UNIQUE INDEX stock_reservations_active_uk ON stock_reservations (order_id, variant_id) WHERE status = 'ACTIVE';
CREATE INDEX stock_reservations_expiry_idx ON stock_reservations (status, expires_at);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL REFERENCES product_variants (id),
    delta INTEGER NOT NULL,
    reason VARCHAR(32) NOT NULL,
    reference_type VARCHAR(32),
    reference_id BIGINT,
    actor_user_id BIGINT REFERENCES users (id),
    balance_after INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT inventory_movements_reason_check CHECK (reason IN ('ORDER', 'CANCEL', 'MANUAL_ADJUST', 'RETURN', 'RESERVE', 'RELEASE'))
);
CREATE INDEX inventory_movements_variant_idx ON inventory_movements (variant_id, created_at DESC);

CREATE TABLE idempotency_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_key VARCHAR(128) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(128) NOT NULL,
    response_status INTEGER,
    response_body JSONB,
    order_id BIGINT REFERENCES orders (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT idempotency_keys_scope_key_uk UNIQUE (scope_key, idempotency_key)
);
CREATE INDEX idempotency_keys_expiry_idx ON idempotency_keys (expires_at);

CREATE TABLE banners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    image_media_id BIGINT NOT NULL REFERENCES media_assets (id),
    link_url VARCHAR(1024),
    display_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ
);

CREATE TABLE notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    priority INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ
);

CREATE TABLE site_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(255) NOT NULL,
    setting_value TEXT,
    value_type VARCHAR(32) NOT NULL DEFAULT 'STRING',
    updated_by BIGINT REFERENCES users (id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT site_settings_key_uk UNIQUE (setting_key)
);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users (id),
    actor_email VARCHAR(255),
    action VARCHAR(32) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id BIGINT,
    before_state JSONB,
    after_state JSONB,
    ip_address VARCHAR(64),
    user_agent VARCHAR(512),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, created_at DESC);
CREATE INDEX audit_log_created_idx ON audit_log (created_at DESC);

CREATE TABLE notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders (id),
    channel VARCHAR(16) NOT NULL,
    recipient VARCHAR(255) NOT NULL,
    template VARCHAR(128) NOT NULL,
    payload JSONB,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ,
    CONSTRAINT notification_outbox_channel_check CHECK (channel IN ('SMS', 'EMAIL')),
    CONSTRAINT notification_outbox_status_check CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);
CREATE INDEX notification_outbox_due_idx ON notification_outbox (status, next_attempt_at);

-- Spring Session JDBC schema (PostgreSQL).
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE
);
