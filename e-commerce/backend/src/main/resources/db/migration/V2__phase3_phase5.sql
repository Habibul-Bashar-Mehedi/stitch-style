-- Phase 3–5 schema: returns, complaints, coupons, reviews and order coupon fields.

ALTER TABLE orders ADD COLUMN coupon_code VARCHAR(64);
ALTER TABLE orders ADD COLUMN coupon_discount NUMERIC(12,2) NOT NULL DEFAULT 0;
ALTER TABLE notification_outbox ADD COLUMN last_error VARCHAR(512);

CREATE TABLE return_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL DEFAULT 'REQUESTED',
    reason TEXT,
    refund_method VARCHAR(32),
    refund_amount NUMERIC(12,2),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT return_requests_status_check CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'RECEIVED', 'REFUNDED'))
);
CREATE INDEX return_requests_order_idx ON return_requests (order_id);
CREATE INDEX return_requests_status_idx ON return_requests (status, requested_at DESC);

CREATE TABLE return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_request_id BIGINT NOT NULL REFERENCES return_requests (id) ON DELETE CASCADE,
    order_item_id BIGINT NOT NULL REFERENCES order_items (id),
    quantity INTEGER NOT NULL,
    condition VARCHAR(32) NOT NULL DEFAULT 'UNOPENED',
    CONSTRAINT return_items_quantity_check CHECK (quantity > 0),
    CONSTRAINT return_items_condition_check CHECK (condition IN ('UNOPENED', 'USED', 'DAMAGED'))
);
CREATE INDEX return_items_request_idx ON return_items (return_request_id);

CREATE TABLE complaints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    phone VARCHAR(32) NOT NULL,
    order_number VARCHAR(64),
    message TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
    due_at TIMESTAMPTZ NOT NULL,
    responded_at TIMESTAMPTZ,
    response TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT complaints_status_check CHECK (status IN ('OPEN', 'RESPONDED', 'CLOSED'))
);
CREATE INDEX complaints_status_idx ON complaints (status, due_at);

CREATE TABLE coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    discount_type VARCHAR(16) NOT NULL,
    discount_value NUMERIC(12,2) NOT NULL,
    min_subtotal NUMERIC(12,2),
    max_uses INTEGER,
    used_count INTEGER NOT NULL DEFAULT 0,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT coupons_code_uk UNIQUE (code),
    CONSTRAINT coupons_discount_type_check CHECK (discount_type IN ('PERCENT', 'FIXED')),
    CONSTRAINT coupons_value_check CHECK (discount_value >= 0)
);

CREATE TABLE coupon_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_id BIGINT NOT NULL REFERENCES coupons (id),
    order_id BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users (id),
    amount NUMERIC(12,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT coupon_redemptions_order_uk UNIQUE (order_id)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rating INTEGER NOT NULL,
    comment TEXT,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    moderated_at TIMESTAMPTZ,
    moderator_id BIGINT REFERENCES users (id),
    CONSTRAINT reviews_rating_check CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT reviews_status_check CHECK (status IN ('PENDING', 'APPROVED', 'HIDDEN')),
    CONSTRAINT reviews_product_user_uk UNIQUE (product_id, user_id)
);
CREATE INDEX reviews_product_status_idx ON reviews (product_id, status, created_at DESC);
